#!/usr/bin/env bash
#=======================================================================================#
# lib/server.sh - server lifecycle: start, stop, restart, monitor, backup, wipe
#
# Also runnable on its own: 'lib/server.sh status' shows the server status.
#=======================================================================================#

if [ -z "${_DAYZ_COMMON_LOADED:-}" ]; then
	. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/common.sh"
fi

# ---------------------------------------------------------------------------
# fn_status_dayz
# Sets dayzstatus to 1 when the tmux session is up, 0 otherwise.
# ---------------------------------------------------------------------------
fn_status_dayz(){
	dayzstatus=$(tmux list-sessions -F "$(whoami)-tmux" 2> /dev/null | grep -Ecx "$(whoami)-tmux")
}

# ---------------------------------------------------------------------------
# fn_clear_logs
# Removes stale .RPT and .log files before a start so the next session's logs
# are easy to find.
#
# .mdmp files are deliberately kept. They are the engine's crash minidumps and
# the single most useful artefact when diagnosing why a server died; the old
# code deleted them on every start, destroying the evidence before anyone
# could look at it.
# ---------------------------------------------------------------------------
fn_clear_logs(){
	local profiles_dir="${HOME}/serverprofile"
	if [ -d "${profiles_dir}" ]; then
		find "${profiles_dir}" -type f \( -name "*.RPT" -o -name "*.log" \) -delete
		printf "[ ${green}DayZ${default} ] Cleared old .RPT and .log files (crash dumps kept).\n"
	fi
}

# ---------------------------------------------------------------------------
# fn_write_launch_wrapper
# Writes the small script tmux actually runs. Launching through a wrapper lets
# us record the server's exit code to ~/last_exit_code, which is otherwise lost
# when the tmux session disappears - and that code is usually the first clue
# about why a server died.
#
# The heredoc is intentionally unquoted so the launch parameters are expanded
# now, producing the exact same command line as a direct invocation. Only "$?"
# is escaped, so it is evaluated by the wrapper after the server exits.
# ---------------------------------------------------------------------------
fn_write_launch_wrapper(){
	local wrapper="${HOME}/.dayz_launch_wrapper.sh"
	cat > "${wrapper}" <<EOF
#!/bin/bash
# Auto-generated by dayzserver.sh - do not edit; it is rewritten on every start.
cd "${HOME}/serverfiles" || exit 1
./DayZServer ${dayzparameter} -mod="${workshop}" -servermod="${servermods}"
echo \$? > "${HOME}/last_exit_code"
EOF
	chmod +x "${wrapper}"
}

# ---------------------------------------------------------------------------
# fn_collect_crashlogs
# Snapshots the evidence after a crash: the newest RPT, the console log, the
# exit code and enough machine state to tell an OOM kill from a game bug.
# ---------------------------------------------------------------------------
fn_collect_crashlogs(){
	local crash_dir latest_rpt
	crash_dir="${HOME}/crashlogs/$(date +%Y-%m-%d_%H-%M-%S)"
	mkdir -p "${crash_dir}"
	printf "[ ${yellow}DayZ${default} ] Collecting crash diagnostics into %s\n" "${crash_dir}"

	# Most recent RPT: full copy plus a short tail that is quick to skim.
	latest_rpt="$(find "${HOME}/serverprofile" -type f -name '*.RPT' -printf '%T@ %p\n' 2>/dev/null \
		| sort -nr | head -n1 | cut -d' ' -f2-)"
	if [ -n "${latest_rpt}" ] && [ -f "${latest_rpt}" ]; then
		cp -f "${latest_rpt}" "${crash_dir}/DayZServer.rpt"
		tail -n 500 "${latest_rpt}" > "${crash_dir}/DayZServer_last500.log"
	else
		echo "No .RPT file found in ${HOME}/serverprofile" > "${crash_dir}/DayZServer_last500.log"
	fi

	# Machine state at the time of the crash - an out-of-memory kill or a full
	# disk shows up here and nowhere else.
	{
		echo "===== free -h ====="; free -h 2>&1
		echo; echo "===== ps aux --sort=-rss (top 30) ====="; ps aux --sort=-rss 2>&1 | head -n 31
		echo; echo "===== df -h ====="; df -h 2>&1
	} > "${crash_dir}/system_state.log" 2>&1

	# Neither of these is guaranteed to be readable by an unprivileged user, so
	# a failure here must never abort the restart.
	journalctl --since "10 minutes ago" > "${crash_dir}/journal.log" 2>&1 \
		|| echo "journalctl unavailable or insufficient permissions" > "${crash_dir}/journal.log"
	dmesg -T > "${crash_dir}/dmesg.log" 2>&1 \
		|| echo "dmesg unavailable or insufficient permissions" > "${crash_dir}/dmesg.log"

	[ -f "${HOME}/tmux.log" ] && cp -f "${HOME}/tmux.log" "${crash_dir}/tmux.log"
	[ -f "${HOME}/last_exit_code" ] && cp -f "${HOME}/last_exit_code" "${crash_dir}/last_exit_code"

	printf "[ ${green}DayZ${default} ] Crash diagnostics saved.\n"
	dayz_crash_dir="${crash_dir}"
	fn_analyze_crashlogs "${crash_dir}"
	fn_prune_crashlogs
}

# ---------------------------------------------------------------------------
# fn_analyze_crashlogs <crash_dir>
# Classifies the likely cause of a crash from the collected evidence, writes
# cause.txt into the crash directory and sets dayz_crash_cause so the caller
# can put the verdict in monitor.log and the Discord alert instead of just
# "the server crashed".
# ---------------------------------------------------------------------------
fn_analyze_crashlogs(){
	local crash_dir="$1" cause="" exit_code=""
	[ -f "${crash_dir}/last_exit_code" ] && exit_code="$(tr -dc '0-9' < "${crash_dir}/last_exit_code")"

	# Most specific explanation wins.
	if grep -qiE 'Out of memory|oom-kill|invoked oom-killer|Killed process' \
		"${crash_dir}/dmesg.log" "${crash_dir}/journal.log" 2>/dev/null; then
		cause="out of memory (see dmesg.log/journal.log)"
	elif grep -qiE 'segfault|general protection|stack overflow|corrupt' \
		"${crash_dir}/dmesg.log" "${crash_dir}/journal.log" 2>/dev/null; then
		cause="native crash (see dmesg.log/journal.log)"
	elif [ "${exit_code}" = "137" ]; then
		cause="killed (exit code 137 - SIGKILL, often the OOM killer)"
	elif [ "${exit_code}" = "139" ]; then
		cause="segfault (exit code 139)"
	elif [ "${exit_code}" = "134" ]; then
		cause="abort (exit code 134 - assertion or glibc abort)"
	elif [ -n "${exit_code}" ] && [ "${exit_code}" != "0" ]; then
		cause="the server exited with code ${exit_code}"
	else
		cause="unknown (no exit code recorded - see DayZServer_last500.log)"
	fi

	printf '%s\n' "${cause}" > "${crash_dir}/cause.txt"
	dayz_crash_cause="${cause}"
	printf "[ ${yellow}DayZ${default} ] Likely cause: %s\n" "${cause}"
}

# ---------------------------------------------------------------------------
# fn_prune_crashlogs
# Keeps only the newest crash_retention_count crash directories. Crash
# evidence is valuable but not priceless - unattended servers generate it
# forever otherwise.
# ---------------------------------------------------------------------------
fn_prune_crashlogs(){
	local keep="${crash_retention_count:-10}" count=0 dir
	while IFS= read -r dir; do
		count=$(( count + 1 ))
		[ "${count}" -le "${keep}" ] && continue
		rm -rf "${dir}"
		fn_info "[ ${lightblue}INFO${default} ] Removed old crash log %s\n" "$(basename "${dir}")"
	done < <(find "${HOME}/crashlogs" -mindepth 1 -maxdepth 1 -type d -printf '%T@ %p\n' 2>/dev/null \
		| sort -rn | cut -d' ' -f2-)
}

# ---------------------------------------------------------------------------
# fn_start_dayz
# Backs up, applies pending updates, clears old logs and launches the server
# in its tmux session.
# ---------------------------------------------------------------------------
fn_start_dayz(){
	local -a refreshed_ids=()
	fn_status_dayz
	if [ "${dayzstatus}" == "1" ]; then
		printf "[ ${yellow}DayZ${default} ] Server already running.\n"
		return 0
	fi

	fn_backup_dayz

	# The README has always promised the server updates itself on restart, so
	# this stays on by default. fn_update_dayz sees a stopped server here and
	# takes its non-restarting branch, so there is no recursion back into start.
	if [ "${auto_update_on_start}" = "1" ]; then
		fn_update_dayz
	fi

	# A `checkmods` run (usually on a cron) leaves this flag when the workshop
	# has newer versions than we hold. Applying them here means downloads happen
	# during the restart window rather than while players are connected.
	if [ -f "${HOME}/update_pending" ]; then
		printf "[ ${yellow}DayZ${default} ] Pending mod updates found; applying before start...\n"
		if fn_workshop_mods; then
			rm -f "${HOME}/update_pending"
			mapfile -t refreshed_ids < <(fn_read_workshop_ids)
			[ "${#refreshed_ids[@]}" -gt 0 ] && fn_refresh_remote_timestamps "${refreshed_ids[@]}"
			printf "[ ${green}DayZ${default} ] Mod updates applied.\n"
		else
			printf "[ ${yellow}WARN${default} ] Some mods failed to update; flag kept for the next start.\n"
		fi
	fi

	fn_clear_logs
	printf "[ ${green}DayZ${default} ] Starting server...\n"

	fn_write_launch_wrapper
	# Start this session's console log fresh. It is archived into the crash
	# directory before every automatic restart, so truncating here is safe and
	# stops the file growing without bound.
	: > "${HOME}/tmux.log"
	tmux new-session -d -x 23 -y 80 -s "$(whoami)-tmux" "${HOME}/.dayz_launch_wrapper.sh"
	sleep 1
	tmux pipe-pane -t "$(whoami)-tmux" -o "cat >> ${HOME}/tmux.log" 2>/dev/null

	date > "${HOME}/.dayzlockfile"

	fn_status_dayz
	if [ "${dayzstatus}" == "1" ]; then
		printf "[ ${green}OK${default} ] Server started.\n"
		fn_log_monitor "Server started successfully."
		return 0
	fi
	printf "[ ${red}FAIL${default} ] Server did not start. Check %s\n" "${HOME}/tmux.log"
	fn_log_monitor "Server start FAILED (no tmux session after launch)."
	return 1
}

# ---------------------------------------------------------------------------
# fn_stop_dayz
# Stops the server gracefully (CTRL+C to the console, 90s grace), falling
# back to killing the tmux session.
# ---------------------------------------------------------------------------
fn_stop_dayz(){
	fn_status_dayz
	if [ "${dayzstatus}" == "1" ]; then
		printf "[ ${magenta}...${default} ] Stopping Server graceful."
		# waits up to 90 seconds giving the server time to shutdown gracefuly
		for seconds in {1..90}; do
			fn_status_dayz
			if [ "${dayzstatus}" == "0" ]; then
				printf "\r[ ${green}OK${default} ] Stopping Server graceful.\n"
				rm -f "${HOME}/.dayzlockfile"
				break
			fi
			printf "\r[ ${magenta}...${default} ] Stopping Server graceful: ${seconds} seconds"
			tmux send-keys C-c -t "$(whoami)-tmux" > /dev/null 2>&1
			sleep 1
		done
		fn_status_dayz
		if [ "${dayzstatus}" != "0" ]; then
			printf "\n[ ${red}FAIL${default} ] Stopping Server graceful failed. Stop Signal.\n"
			sleep 2
			rm -f "${HOME}/.dayzlockfile"
			tmux kill-session -t "$(whoami)-tmux"
			#killall -u $(whoami)
		fi
	else
		printf "[ ${yellow}DayZ${default} ] Server not running.\n"
	fi
}

# ---------------------------------------------------------------------------
# fn_restart_dayz
# ---------------------------------------------------------------------------
fn_restart_dayz(){
	fn_stop_dayz
	sleep 1
	fn_start_dayz
}

# ---------------------------------------------------------------------------
# fn_monitor_dayz
# Cron/systemd entry point: restarts the server when the lockfile says it
# should be up but the session is gone. Crash evidence is collected BEFORE
# the restart, because the restart truncates tmux.log and overwrites the RPT.
# ---------------------------------------------------------------------------
fn_monitor_dayz(){
	if [ -f "${HOME}/.dayzlockupdate" ]; then
		printf "[ ${yellow}INFO${default} ] Server files are being updated; skipping this check.\n"
		return 0
	fi

	fn_status_dayz
	if [ "${dayzstatus}" == "0" ] && [ -f "${HOME}/.dayzlockfile" ]; then
		# Gather diagnostics BEFORE restarting - the restart truncates tmux.log
		# and the server overwrites its RPT.
		fn_log_monitor "Server crashed. Restart initiated."
		fn_collect_crashlogs
		fn_log_monitor "Likely cause: ${dayz_crash_cause:-unknown}"
		fn_discord_notify "DayZ server crashed (${dayz_crash_cause:-unknown cause}); restarting automatically. Logs: ${dayz_crash_dir:-~/crashlogs}"
		fn_restart_dayz
	elif [ "${dayzstatus}" != "0" ] && [ -f "${HOME}/.dayzlockfile" ]; then
		printf "[ ${lightblue}INFO${default} ] Server is online.\n"
	else
		printf "[ ${yellow}INFO${default} ] Server is stopped on purpose. Use '%s start' to start it.\n" "$0"
	fi
	return 0
}

# ---------------------------------------------------------------------------
# fn_console_dayz
# Attaches to the tmux session running the server.
# ---------------------------------------------------------------------------
fn_console_dayz(){
	printf "[${yellow} Warning ${default}] Press \"CTRL+b\" then \"d\" to exit console.\n    Do NOT press CTRL+c to exit.\n\n"
	sleep 0.1
	while true; do
		read -e -i "Y" -p "Continue? [Y/n] " -r answer
		case "${answer}" in
			[Yy]|[Yy][Ee][Ss]) tmux a -t "$(whoami)-tmux"
			                   return 0;;
			[Nn]|[Nn][Oo]) return 1 ;;
			*) echo "Please answer yes or no." ;;
		esac
	done
}

# ---------------------------------------------------------------------------
# fn_missionfolder
# Reads the mission template name from serverDZ.cfg.
# ---------------------------------------------------------------------------
fn_missionfolder(){
	local cfg="${HOME}/serverfiles/${config}"
	[ -f "${cfg}" ] || return 1
	# The template line is indented inside the Missions class, so take the text
	# between the quotes rather than counting fields - a positional cut lands on
	# the "=" when the line has leading whitespace.
	grep -iE '^[[:space:]]*template[[:space:]]*=' "${cfg}" | head -n1 | cut -d '"' -f2
}

# ---------------------------------------------------------------------------
# fn_backup_dayz
# Tars the mission folder and the server profile (gzip-compressed and verified
# after writing), then prunes old backups by age AND by count - a broken cron
# timestamp must not be able to delete everything, and a healthy one must not
# grow the archive pile without bound. The server is stopped first when
# running so the copy is consistent. Restore with 'main.sh restore'.
# ---------------------------------------------------------------------------
fn_backup_dayz(){
	if [ "${backup_in_progress:-0}" = "1" ]; then
		return 0
	fi
	local backup_in_progress=1
	local missionfolder backup_file profile_backup_file was_running=0

	mkdir -p "${HOME}/backup"
	fn_warn_disk "${HOME}/backup" "${min_free_mb:-2048}" "backups"

	missionfolder="$(fn_missionfolder)"
	if [ -z "${missionfolder}" ]; then
		printf "[ ${yellow}WARN${default} ] No mission template found in ${config}; skipping mission backup.\n"
	fi

	fn_status_dayz
	if [ "${dayzstatus}" != "0" ]; then
		was_running=1
		printf "[ ${yellow}DayZ${default} ] Server is running; stopping it for a consistent backup...\n"
		fn_stop_dayz
	fi

	backup_file="${HOME}/backup/${missionfolder}-$(date +%Y-%m-%d-%H-%M).tar.gz"
	profile_backup_file="${HOME}/backup/serverprofile-$(date +%Y-%m-%d-%H-%M).tar.gz"

	if [ -n "${missionfolder}" ] && [ -d "${HOME}/serverfiles/mpmissions/${missionfolder}" ]; then
		printf "[ ${green}DayZ${default} ] Backing up mission folder: ${cyan}%s${default}\n" "${missionfolder}"
		tar -czf "${backup_file}" -C "${HOME}/serverfiles/mpmissions" "${missionfolder}"
		fn_backup_verify "${backup_file}"
	fi

	if [ -d "${HOME}/serverprofile" ]; then
		printf "[ ${green}DayZ${default} ] Backing up server profile: ${cyan}%s${default}\n" "${HOME}/serverprofile"
		tar --exclude='*.log' --exclude='*.RPT' --exclude='*.mdmp' \
			-czf "${profile_backup_file}" -C "${HOME}" "serverprofile"
		fn_backup_verify "${profile_backup_file}"
	fi

	printf "[ ${green}DayZ${default} ] Pruning backups older than %s day(s), keeping %s per kind...\n" \
		"${backup_retention_days}" "${backup_retention_count}"
	find "${HOME}/backup" -type f \( -name '*.tar' -o -name '*.tar.gz' \) \
		-mtime "+${backup_retention_days}" -delete 2>/dev/null
	fn_backup_prune "mission" "${backup_retention_count}"
	fn_backup_prune "profile" "${backup_retention_count}"

	if [ "${was_running}" = "1" ]; then
		printf "[ ${green}DayZ${default} ] Restoring the server after backup...\n"
		fn_start_dayz
	fi
}

# ---------------------------------------------------------------------------
# fn_backup_verify <archive>
# A backup that cannot be read is not a backup. The archive is listed right
# after writing so a full disk or broken gzip is caught now, not at restore.
# ---------------------------------------------------------------------------
fn_backup_verify(){
	local archive="$1"
	if tar -tzf "${archive}" > /dev/null 2>&1; then
		printf "[ ${green}OK${default} ] Backup verified: %s\n" "$(basename "${archive}")"
	else
		printf "[ ${red}FAIL${default} ] Backup archive is unreadable: %s\n" "${archive}"
		rm -f "${archive}"
		return 1
	fi
}

# ---------------------------------------------------------------------------
# fn_backup_prune <mission|profile> <keep>
# Keeps only the <keep> newest archives of one kind and deletes the rest.
# Old .tar archives (pre-compression) count too.
# ---------------------------------------------------------------------------
fn_backup_prune(){
	local kind="$1" keep="$2" f count=0
	local -a files=()
	for f in "${HOME}/backup"/*.tar "${HOME}/backup"/*.tar.gz; do
		[ -f "${f}" ] || continue
		if [ "${kind}" = "profile" ]; then
			case "$(basename "${f}")" in serverprofile-*) files+=("${f}") ;; esac
		else
			case "$(basename "${f}")" in serverprofile-*) continue ;; esac
			files+=("${f}")
		fi
	done
	[ "${#files[@]}" -gt 0 ] || return 0

	# ls -1t sorts by modification time, newest first.
	while IFS= read -r f; do
		count=$(( count + 1 ))
		[ "${count}" -le "${keep}" ] && continue
		rm -f "${f}"
		printf "[ ${lightblue}INFO${default} ] Removed old backup %s\n" "$(basename "${f}")"
	done < <(ls -1t "${files[@]}" 2>/dev/null)
}

# ---------------------------------------------------------------------------
# fn_restore_dayz [archive]
# Restores a backup archive made by `backup`, detecting from its contents
# whether it is a mission or a serverprofile archive. With no argument the
# available archives are listed. A fresh pre-restore snapshot is taken first,
# so restoring the wrong archive is never the last word.
# ---------------------------------------------------------------------------
fn_restore_dayz(){
	local archive="${1:-}"
	local backup_dir="${HOME}/backup"

	if [ -z "${archive}" ]; then
		printf "\n${lightyellow}Available backups${default}\n"
		local f found=0
		for f in "${backup_dir}"/*.tar.gz "${backup_dir}"/*.tar; do
			[ -f "${f}" ] || continue
			printf "  %s\n" "$(basename "${f}")"
			found=1
		done
		[ "${found}" = "1" ] || printf "  (none - run '%s backup' first)\n" "$0"
		printf "\nUsage: %s restore <archive>\n\n" "$0"
		return 0
	fi

	if [ ! -f "${archive}" ]; then
		if [ -f "${backup_dir}/${archive}" ]; then
			archive="${backup_dir}/${archive}"
		else
			printf "[ ${red}FAIL${default} ] Backup archive not found: %s\n" "${archive}"
			return 1
		fi
	fi

	# The archive itself decides where it goes - the filename is not trusted.
	local first_entry kind
	first_entry="$(tar -tzf "${archive}" 2>/dev/null | sed -n '1p')"
	[ -n "${first_entry}" ] || first_entry="$(tar -tf "${archive}" 2>/dev/null | sed -n '1p')"
	if [ -z "${first_entry}" ]; then
		printf "[ ${red}FAIL${default} ] Archive is unreadable: %s\n" "${archive}"
		return 1
	fi
	case "${first_entry}" in
		serverprofile|serverprofile/*) kind="profile" ;;
		*)                            kind="mission" ;;
	esac

	printf "[ ${red}WARNING${default} ] This restores ${cyan}%s${default} (${kind}) and OVERWRITES the current %s data.\n" \
		"$(basename "${archive}")" "${kind}"
	read -r -p "Type 'yes' to continue: " confirm
	if [ "${confirm}" != "yes" ]; then
		printf "[ ${lightblue}INFO${default} ] Aborted; nothing was restored.\n"
		return 1
	fi

	fn_status_dayz
	local was_running=0
	if [ "${dayzstatus}" != "0" ]; then
		was_running=1
		printf "[ ${yellow}DayZ${default} ] Stopping the server first...\n"
		fn_stop_dayz
	fi

	# Snapshot the current state before overwriting it.
	printf "[ ${lightblue}INFO${default} ] Taking a pre-restore snapshot...\n"
	fn_backup_dayz

	local -a tar_opts=(-xf)
	tar -tzf "${archive}" > /dev/null 2>&1 && tar_opts=(-xzf)
	if [ "${kind}" = "profile" ]; then
		mkdir -p "${HOME}"
		tar "${tar_opts[@]}" "${archive}" -C "${HOME}" || {
			printf "[ ${red}FAIL${default} ] Restore failed. The pre-restore snapshot is in %s\n" "${HOME}/backup"
			return 1
		}
	else
		mkdir -p "${HOME}/serverfiles/mpmissions"
		tar "${tar_opts[@]}" "${archive}" -C "${HOME}/serverfiles/mpmissions" || {
			printf "[ ${red}FAIL${default} ] Restore failed. The pre-restore snapshot is in %s\n" "${HOME}/backup"
			return 1
		}
	fi

	printf "[ ${green}OK${default} ] Restored %s\n" "$(basename "${archive}")"
	fn_log_monitor "Restored backup $(basename "${archive}") (${kind})."
	fn_discord_notify "DayZ backup restored: $(basename "${archive}") (${kind})."

	if [ "${was_running}" = "1" ]; then
		printf "[ ${green}DayZ${default} ] Restarting the server...\n"
		fn_start_dayz
	fi
	return 0
}
# ---------------------------------------------------------------------------
# fn_wipe_dayz
# Deletes players.db and the storage data of the configured mission.
# ---------------------------------------------------------------------------
fn_wipe_dayz(){
	local missionfolder storage
	missionfolder="$(fn_missionfolder)"
	if [ -z "${missionfolder}" ]; then
		printf "[ ${red}FAIL${default} ] Could not determine the mission folder from ${config}.\n"
		return 1
	fi
	storage="${HOME}/serverfiles/mpmissions/${missionfolder}/storage_1"

	printf "[ ${red}WARNING${default} ] This wipes all players and resets the Central Economy state.\n"
	for seconds in {9..0}; do
		printf "\r\t    Mission: ${cyan}%s${default} - wiping in ${red}%s${default} seconds. Press CTRL+C to abort." \
			"${missionfolder}" "${seconds}"
		sleep 1
	done
	printf "\n"

	fn_status_dayz
	local was_running=0
	if [ "${dayzstatus}" != "0" ]; then
		was_running=1
		fn_stop_dayz
	fi

	rm -f "${storage}/players.db"
	rm -rf "${storage:?}/data/"*
	printf "[ ${yellow}DayZ${default} ] players.db and storage data wiped.\n"
	fn_log_monitor "Server data wiped (mission: ${missionfolder})."

	if [ "${was_running}" = "1" ]; then
		sleep 0.5
		fn_start_dayz
	fi
}

# ---------------------------------------------------------------------------
# fn_clean_server
# Deletes everything except the Steam authorisation, for a fresh install.
# ---------------------------------------------------------------------------
fn_clean_server(){
	printf "[ ${red}WARNING${default} ] This deletes the server files, mods, profiles, backups and %s.\n" "${CONFIG_FILE}"
	printf "[ ${lightblue}INFO${default} ] Your Steam authorisation is preserved.\n"
	read -r -p "Type 'yes' to continue: " confirm
	if [ "${confirm}" != "yes" ]; then
		printf "[ ${lightblue}INFO${default} ] Aborted; nothing was deleted.\n"
		return 1
	fi

	fn_status_dayz
	if [ "${dayzstatus}" != "0" ]; then
		printf "[ ${yellow}DayZ${default} ] Stopping the server first...\n"
		fn_stop_dayz
	fi

	local d f
	for d in "${HOME}/serverfiles" "${HOME}/serverprofile" "${HOME}/steamcmd" \
	         "${HOME}/backup" "${HOME}/crashlogs" "${HOME}/.dayz.runlock"; do
		if [ -e "${d}" ]; then
			rm -rf "${d}"
			printf "[ ${green}OK${default} ] Removed %s\n" "${d}"
		fi
	done
	for f in "${HOME}/${CONFIG_FILE}" "${HOME}/workshop.cfg" "${HOME}/mod_timestamps.json" \
	         "${HOME}/mod_remote_timestamps.json" "${HOME}/update_pending" \
	         "${HOME}/.dayzlockfile" "${HOME}/.dayzlockupdate" "${HOME}/monitor.log" \
	         "${HOME}/tmux.log" "${HOME}/last_exit_code" "${HOME}/.dayz_launch_wrapper.sh" \
	         "${HOME}/.steam_api_cache.json" "${HOME}/.steam_api.lock" \
	         "${HOME}/.build_check_cache" "${HOME}/.steamcmd_last_run" \
	         "${HOME}/.dayzweb.pid" "${HOME}/dayzweb.log"; do
		if [ -e "${f}" ]; then
			rm -f "${f}"
			printf "[ ${green}OK${default} ] Removed %s\n" "${f}"
		fi
	done

	printf "[ ${green}DayZ${default} ] Cleanup complete. Steam authorisation preserved.\n"
	return 0
}

# ---------------------------------------------------------------------------
# fn_server_uptime
# Seconds since the lockfile was written (i.e. since the last start).
# ---------------------------------------------------------------------------
fn_server_uptime(){
	local started now
	[ -f "${HOME}/.dayzlockfile" ] || { printf '0'; return; }
	started="$(date -r "${HOME}/.dayzlockfile" +%s 2>/dev/null || echo 0)"
	now="$(date +%s)"
	printf '%s' "$(( now - started ))"
}

