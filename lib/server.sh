	. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/steam.sh"
	. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/workshop.sh"
	. "$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/query.sh"
	fn_apply_defaults
	case "${1:-}" in
		status)     fn_status_dayz_report ;;
		start)      fn_start_dayz ;;
		stop)       fn_stop_dayz ;;
		restart)    fn_restart_dayz ;;
		monitor)    fn_monitor_dayz ;;
		console)    fn_console_dayz ;;
		backup)     fn_backup_dayz ;;
		wipe)       fn_wipe_dayz ;;
		cleanserver) fn_clean_server ;;
		*) printf '%s\n' \
			"lib/server.sh - server lifecycle: start, stop, restart, monitor, backup, wipe." \
			"Usage: lib/server.sh {status|start|stop|restart|monitor|console|backup|wipe|cleanserver}" ;;
	esac
fi
